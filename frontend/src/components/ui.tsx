import { useEffect, useRef, type ReactNode } from "react";
import { AlertTriangle, CircleDashed, FlaskConical, HelpCircle, Sparkles, UtensilsCrossed, WifiOff, X } from "lucide-react";
import { HEALTH_LABEL, isUncertain, tableLook } from "../lib/format";
import type { Health, TableView } from "../types/api";

export function Card({ title, icon, actions, children, className = "", pad = true }: {
  title?: ReactNode;
  icon?: ReactNode;
  actions?: ReactNode;
  children: ReactNode;
  className?: string;
  pad?: boolean;
}) {
  return (
    <section className={`card ${className}`}>
      {(title || actions) && (
        <header className="flex items-center justify-between gap-3 border-b border-ink-700/70 px-4 py-3 sm:px-5">
          <h2 className="flex items-center gap-2 text-sm font-semibold text-txt">
            {icon}
            {title}
          </h2>
          {actions && <div className="flex items-center gap-2">{actions}</div>}
        </header>
      )}
      <div className={pad ? "card-pad" : ""}>{children}</div>
    </section>
  );
}

export function SimBadge({ compact = false }: { compact?: boolean }) {
  return (
    <span
      className="chip border-fuchsia-400/50 bg-fuchsia-500/15 text-fuchsia-100"
      title="Everything shown is generated by the deterministic simulator. It is not real footage or real restaurant data."
    >
      <FlaskConical className="h-3.5 w-3.5" aria-hidden />
      {compact ? "SIMULATED" : "SIMULATED DATA"}
    </span>
  );
}

export function StateBadge({ table }: { table: TableView }) {
  const look = tableLook(table);
  const Icon =
    table.state === "FREE" ? Sparkles : table.state === "NEEDS_CLEANING" ? CircleDashed : table.unserved_overdue ? AlertTriangle : UtensilsCrossed;
  return (
    <span className={`chip ${look.border} ${look.bg} ${look.text}`}>
      <Icon className="h-3.5 w-3.5" aria-hidden />
      {look.label}
    </span>
  );
}

export function HealthBadge({ health }: { health: Health }) {
  if (!isUncertain(health))
    return <span className="chip border-emerald-400/30 bg-emerald-400/10 text-emerald-200">{HEALTH_LABEL[health]}</span>;
  const Icon = health === "OFFLINE" ? WifiOff : HelpCircle;
  return (
    <span className="chip border-slate-400/40 bg-slate-400/10 text-slate-200">
      <Icon className="h-3.5 w-3.5" aria-hidden />
      {HEALTH_LABEL[health]}
    </span>
  );
}

export function Toggle({ checked, onChange, label, id }: { checked: boolean; onChange: (v: boolean) => void; label: string; id: string }) {
  return (
    <label htmlFor={id} className="inline-flex cursor-pointer select-none items-center gap-2 text-sm text-txt-muted">
      <span className="relative inline-flex">
        <input id={id} type="checkbox" className="peer sr-only" checked={checked} onChange={(e) => onChange(e.target.checked)} />
        <span className="h-5 w-9 rounded-full bg-ink-600 transition peer-checked:bg-brand/80 peer-focus-visible:ring-2 peer-focus-visible:ring-brand/60" />
        <span className="absolute left-0.5 top-0.5 h-4 w-4 rounded-full bg-white transition peer-checked:translate-x-4" />
      </span>
      {label}
    </label>
  );
}

export function Modal({ open, title, onClose, children, wide = false }: {
  open: boolean;
  title: string;
  onClose: () => void;
  children: ReactNode;
  wide?: boolean;
}) {
  const ref = useRef<HTMLDivElement>(null);
  useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => e.key === "Escape" && onClose();
    window.addEventListener("keydown", onKey);
    ref.current?.querySelector<HTMLElement>("input,select,textarea,button")?.focus();
    return () => window.removeEventListener("keydown", onKey);
  }, [open, onClose]);
  if (!open) return null;
  return (
    <div className="fixed inset-0 z-40 flex items-center justify-center bg-ink-950/70 p-4 backdrop-blur-sm" onMouseDown={onClose}>
      <div
        ref={ref}
        role="dialog"
        aria-modal="true"
        aria-label={title}
        className={`card animate-in w-full ${wide ? "max-w-3xl" : "max-w-md"} max-h-[90vh] overflow-auto`}
        onMouseDown={(e) => e.stopPropagation()}
      >
        <header className="flex items-center justify-between border-b border-ink-700 px-5 py-3">
          <h2 className="text-base font-semibold">{title}</h2>
          <button className="btn-ghost p-1" onClick={onClose} aria-label="Close">
            <X className="h-4 w-4" />
          </button>
        </header>
        <div className="p-5">{children}</div>
      </div>
    </div>
  );
}

export function Empty({ title, body, icon }: { title: string; body?: ReactNode; icon?: ReactNode }) {
  return (
    <div className="flex flex-col items-center justify-center gap-2 rounded-lg border border-dashed border-ink-600 px-6 py-10 text-center">
      {icon}
      <p className="text-sm font-medium text-txt">{title}</p>
      {body && <div className="max-w-md text-xs text-txt-muted">{body}</div>}
    </div>
  );
}

export function ErrorText({ error }: { error: string | null | undefined }) {
  if (!error) return null;
  return (
    <p role="alert" className="mt-2 rounded-lg border border-red-400/40 bg-red-500/10 px-3 py-2 text-sm text-red-200">
      {error}
    </p>
  );
}

export function Stat({ label, value, sub, icon, tone = "text-txt", testId }: {
  label: string;
  value: ReactNode;
  sub?: ReactNode;
  icon?: ReactNode;
  tone?: string;
  testId?: string;
}) {
  return (
    <div className="card flex flex-col gap-1 px-4 py-3.5" data-testid={testId}>
      <div className="flex items-center justify-between text-xs font-medium uppercase tracking-wide text-txt-muted">
        {label}
        <span className="opacity-80">{icon}</span>
      </div>
      <div className={`text-2xl font-semibold tabular-nums ${tone}`}>{value}</div>
      {sub && <div className="text-xs text-txt-faint">{sub}</div>}
    </div>
  );
}
